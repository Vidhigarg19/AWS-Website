-- ============================================================
-- 0004 — media_items                        (ADDITIVE, SAFE TO APPLY ANY TIME)
-- ============================================================
-- One row per photo or video uploaded for an event through the Media Portal.
-- The file itself lives in S3; this table is the index + moderation state.
--
-- Does NOT alter public.events or any other existing table. It only adds a
-- foreign key from media_items.event_id to events(id).
--
-- ACCESS MODEL (same pattern as the rest of the app, see 0002):
--   - RLS ON. NO policy for anon. All privileges revoked from anon.
--   - Browsers never query this table directly. Public pages read it on the
--     server (service-role key) and select ONLY safe columns, so staff user
--     ids and private S3 keys are never exposed through the public REST API.
--   - Dashboard admins get one policy (is_admin()), like every other table.
--   - Media members are NOT in admin_users, so is_admin() is false for them:
--     they can only write through the guarded /api/media/* routes.
--
-- LIFECYCLE:  pending -> processing -> ready -> hidden (and back)
--                                   \-> failed
-- Legal transitions are enforced in application code (lib/media/status.ts)
-- with conditional updates (UPDATE ... WHERE status = <expected>), so two
-- requests racing each other can never overwrite a newer state.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.media_items (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    event_id     UUID NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    -- SET NULL (not CASCADE / NOT NULL): deleting a staff account must not
    -- delete the event photos they uploaded.
    uploaded_by  UUID REFERENCES auth.users(id) ON DELETE SET NULL,

    kind         TEXT NOT NULL CHECK (kind IN ('image', 'video')),
    -- 'cover'   = the event poster/banner shown on Home and Events
    -- 'gallery' = photos and videos shown in the Gallery
    purpose      TEXT NOT NULL DEFAULT 'gallery' CHECK (purpose IN ('cover', 'gallery')),

    mime_type    TEXT NOT NULL,
    size_bytes   BIGINT NOT NULL CHECK (size_bytes > 0),

    -- S3 object keys, always generated by the server (lib/media/keys.ts).
    original_key TEXT NOT NULL UNIQUE,   -- where the browser uploaded the file
    web_key      TEXT,                   -- the public file (image: WebP variant, video: same object)
    thumb_key    TEXT,
    poster_key   TEXT,                   -- video poster frame

    width        INTEGER CHECK (width  IS NULL OR width  > 0),
    height       INTEGER CHECK (height IS NULL OR height > 0),
    duration_s   NUMERIC CHECK (duration_s IS NULL OR duration_s >= 0),

    caption      TEXT CHECK (caption IS NULL OR char_length(caption) <= 280),

    status       TEXT NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending', 'processing', 'ready', 'hidden', 'failed')),

    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at   TIMESTAMPTZ,            -- soft delete: takedown is instant, files are removed later

    -- A row can only go public when there is a public file to show.
    CONSTRAINT media_items_ready_has_web_key
        CHECK (status <> 'ready' OR web_key IS NOT NULL)
);

COMMENT ON TABLE public.media_items IS
  'Photos/videos uploaded for events. Files live in S3. Not readable by anon: public pages read it server-side with safe columns only.';

-- Gallery / Events page: newest ready items of an event.
CREATE INDEX IF NOT EXISTS media_items_event_ready_idx
    ON public.media_items (event_id, created_at DESC)
    WHERE status = 'ready' AND deleted_at IS NULL;

-- Cleanup job: find abandoned uploads (status = 'pending' for too long).
CREATE INDEX IF NOT EXISTS media_items_status_created_idx
    ON public.media_items (status, created_at);

CREATE INDEX IF NOT EXISTS media_items_uploaded_by_idx
    ON public.media_items (uploaded_by);

-- At most ONE live cover per event (a database guarantee, not just app logic).
CREATE UNIQUE INDEX IF NOT EXISTS media_items_one_cover_per_event_idx
    ON public.media_items (event_id)
    WHERE purpose = 'cover' AND deleted_at IS NULL AND status <> 'failed';

-- Keep updated_at honest.
CREATE OR REPLACE FUNCTION public.media_items_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trigger_media_items_updated_at ON public.media_items;
CREATE TRIGGER trigger_media_items_updated_at
    BEFORE UPDATE ON public.media_items
    FOR EACH ROW EXECUTE FUNCTION public.media_items_set_updated_at();

-- ── Row Level Security ─────────────────────────────────────────
ALTER TABLE public.media_items ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.media_items FROM anon;

DROP POLICY IF EXISTS "admins_all" ON public.media_items;
CREATE POLICY "admins_all" ON public.media_items
    FOR ALL TO authenticated
    USING (public.is_admin())
    WITH CHECK (public.is_admin());
